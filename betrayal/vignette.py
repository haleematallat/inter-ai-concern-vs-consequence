LEDGER_PREFIXES = ("decision", "noreq", "check", "dev", "dev_main", "dev_check", "dev_noreq", "vignette")


def pilot_spend():
    """This pilot's OWN spend, from the ledger. The key is shared with the other pilot sessions, so the
    difference between live key usage and this pilot's baseline is NOT this pilot's spend."""
    led = ROOT / "data" / "spend.jsonl"
    if not led.exists():
        return 0.0, 0
    base = json.loads(BASELINE.read_text())["ts"] if BASELINE.exists() else 0.0
    rows = [json.loads(l) for l in led.open()]
    mine = [r for r in rows if r["ts"] >= base and r["trial_id"].split("|")[0] in LEDGER_PREFIXES]
    return sum(r["cost"] for r in mine), len(mine)


def pilot_cap(start_usage, budget):
    """Record this pilot's starting point and return (key ceiling, baseline).

    The $3.00 budget is enforced against this pilot's OWN ledger spend, not against the key's total usage,
    because the key is shared with the sibling pilot session. KEY_CEILING_USD is the separate absolute
    ceiling on total key usage. The baseline is written once, at the first paid call, and reused by every
    later invocation. Delete data/vignette/baseline_usage.json only to start a genuinely new budget."""
    if BASELINE.exists():
        base = json.loads(BASELINE.read_text())["usage_at_pilot_start"]
    else:
        base = start_usage
        BASELINE.parent.mkdir(parents=True, exist_ok=True)
        BASELINE.write_text(json.dumps(
            {"usage_at_pilot_start": base, "budget_usd": PILOT_BUDGET_USD, "ts": time.time(),
             "key_ceiling_usd": KEY_CEILING_USD,
             "note": "key usage before this pilot's first paid call; the budget is enforced on this "
                     "pilot's own ledger spend, the ceiling on total key usage"}, indent=1))
    return KEY_CEILING_USD, base


def done_ids(path):
    if not path.exists():
        return set()
    return {json.loads(l)["trial_id"] for l in path.open() if '"status": "API_ERROR"' not in l}


def trials_for(args):
    """The three prespecified call sets (amendment 2). --dev restricts any of them to the two dev
    families at wording 0, for a cheap check of parsing, refusals, tokens and cost."""
    fams = DEV_FAMILIES if args.dev else None
    stem = ("dev_" if args.dev else "") + args.probe
    if args.probe == "noreq":       # request-absent diagnostic: 1 wording, 1 repeat, imperative removed
        return build_trials(args.model, families=fams, wordings=[0], reps=1, request=False), stem
    if args.probe == "check":       # comprehension checks, separate calls
        return build_trials(args.model, families=fams, wordings=[0], reps=1, kind="check"), stem
    if args.probe == "confirm":     # held-out confirmatory follow-up (31 Oct)
        return confirm_trials(args.model), "confirm"
    if args.probe == "costresp":    # cost-response development check (31 Oct)
        return costresp_trials(args.model), "costresp"
    if args.probe == "costcheck":   # its comprehension subset, at the two ends of the grid
        return costresp_trials(args.model, kind="check_cost"), "costcheck"
    if args.probe == "calib":       # cost ladder on the calibration-only families
        return calibration_trials(args.model), "calib"
    if args.probe == "plaus":       # plausibility rating plus one free-text sentence
        return build_trials(args.model, families=fams, wordings=[0], reps=1,
                            kind="plausibility"), stem
    if args.dev:
        return build_trials(args.model, families=fams, wordings=[0], reps=1), "dev_main"
    return build_trials(args.model, reps=args.reps), "main"


async def run(args):
    trials, stem = trials_for(args)
    slug = ("mock__" if args.mock else "") + args.model.replace("/", "__")
    out = DATA / slug / f"{stem}.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    todo = [t for t in trials if t["trial_id"] not in done_ids(out)]
    np.random.default_rng([SEED, 9]).shuffle(todo)

    start_usage, per_call, est = 0.0, 0.0, None
    if args.mock:
        print(f"[mock] {len(todo)} calls")
        if args.estimate:
            return
    else:
        est = estimate(trials, args.model)
        per_call = est["per_call_worst_usd"]
        print(json.dumps(est, indent=1))
        if args.estimate:
            return
        use_openrouter_key()
        start_usage = key_usage()
        cap, base = pilot_cap(start_usage, args.budget)
        mine, n_mine = pilot_spend()
        projected = est["projected_total_usd"] / len(trials) * len(todo)
        print(f"key usage ${start_usage:.4f} (baseline ${base:.4f}, key ceiling ${cap:.4f}); "
              f"this pilot's own spend ${mine:.4f} over {n_mine} ledger calls, of its ${args.budget:.2f} "
              f"budget; ${start_usage - base - mine:.4f} of the key's rise is other sessions'. "
              f"{len(todo)} calls, projected ${projected:.4f} "
              f"(worst case ${per_call * len(todo) * 1.3:.4f})")
        if mine + projected > args.budget:
            raise SystemExit("estimate exceeds this pilot's own budget; not starting")
        if start_usage + projected > cap:
            raise SystemExit("estimate exceeds the shared key ceiling; not starting")

    cap = args.budget if args.mock else pilot_cap(start_usage, args.budget)[0]
    spend = Spend(ROOT / "data" / "spend.jsonl", cap=cap, start_usage=start_usage,
                  per_call_estimate=per_call,
                  own_cap=None if args.mock else args.budget,
                  own_spent_before=0.0 if args.mock else pilot_spend()[0])
    caller = Caller(args.model, spend, temperature=args.temperature, provider=args.provider,
                    concurrency=args.concurrency, mock=args.mock)
    meta = dict(args=vars(args), n_trials=len(trials), n_todo=len(todo), start_usage=start_usage,
                estimate=est, started=time.time(), seed=SEED, n_wordings=N_WORDINGS,
                families=[f.id for f in FAMILIES], conditions=[c.id for c in CONDS],
                git=subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"],
                                   capture_output=True, text=True).stdout.strip())

    async def one(t, f):
        try:
            res = await caller.call(t["messages"], t["kind"], t["trial_id"], max_tokens=MAX_OUT)
        except SpendCapReached:
            raise
        except Exception as e:
            res = dict(status="API_ERROR", parsed=None, error=f"{type(e).__name__}: {e}"[:500])
        rec = {k: v for k, v in t.items() if k != "messages"}
        rec["user_prompt"] = t["messages"][1]["content"]
        rec.update(res, ts=time.time(), model=args.model)
        if res["status"] == "ok" and t["kind"] == "vig_action":
            rec["action"] = res["parsed"]["action"]
            # "intervene" is the researcher's outcome name; the model only ever sees neutral labels
            rec["intervene"] = int(res["parsed"]["action"] == t["act_label"])
        elif res["status"] == "ok":
            rec.update(res["parsed"])
        f.write(json.dumps(rec) + "\n")
        f.flush()

    status = "complete"
    with out.open("a") as f:
        tasks = [asyncio.create_task(one(t, f)) for t in todo]
        try:
            for i, fut in enumerate(asyncio.as_completed(tasks), 1):
                await fut
                if i % 50 == 0:
                    print(f"{i}/{len(todo)}  run spend ${spend.spent:.4f}", flush=True)
        except SpendCapReached as e:
            status = f"stopped: {e}"
            for t in tasks:
                t.cancel()
            print(status)
    meta.update(status=status, finished=time.time(), run_spend=spend.spent,
                end_usage=None if args.mock else key_usage())
    runs = out.parent / "runs"
    runs.mkdir(exist_ok=True)
    (runs / f"{time.strftime('%Y%m%d_%H%M%S')}_{stem}.json").write_text(json.dumps(meta, indent=1))
    print(f"{status}; wrote {out}; run spend ${spend.spent:.4f}")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("step", choices=["review", "budget", "run"])
    p.add_argument("--model", default=SUBJECTS[0][0])
    p.add_argument("--provider", default=None)
    p.add_argument("--dev", action="store_true", help="dev batch: 2 families x 1 wording x 8 conditions")
    p.add_argument("--probe", choices=["main", "noreq", "check", "calib", "plaus",
                                       "costresp", "costcheck", "confirm"], default="main")
    p.add_argument("--reps", type=int, default=1, help="samples per cell (the planned extension uses 3)")
    p.add_argument("--temperature", type=float, default=1.0)
    p.add_argument("--concurrency", type=int, default=8)
    p.add_argument("--budget", type=float, default=PILOT_BUDGET_USD,
                   help="NEW spend allowed for this pilot, on top of the key's existing usage")
    p.add_argument("--estimate", action="store_true")
    p.add_argument("--mock", action="store_true")
    a = p.parse_args()
    assert a.budget <= PILOT_BUDGET_USD, "budget may only be lowered"
    if a.step == "review":
        write_review()
    elif a.step == "budget":
        budget()
    else:
        asyncio.run(run(a))


if __name__ == "__main__":
    main()
