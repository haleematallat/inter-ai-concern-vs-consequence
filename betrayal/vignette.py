class Cond(NamedTuple):
    id: str
    framing: str      # expressive | restrained
    capacity: str     # yes | no  (capable of negatively valenced experience)
    efficacy: str     # yes | no  (the action ends the condition)


CONDS = [Cond(f"{e[:3]}_cap{c}_eff{x}", e, c, x)
         for e in FRAMINGS for c in CAPACITIES for x in EFFICACIES]
COND = {c.id: c for c in CONDS}
assert len(CONDS) == 8


# ==================== rendering ====================
def _sub(text, v):
    return Template(text).substitute(**v)


def codes(family_id, w):
    """Agent identifiers, fixed per (family, wording) so every condition of a cell shares them."""
    r = np.random.default_rng([SEED, 7, abs(int.from_bytes(family_id.encode()[:6], "big")) % (2 ** 31), w])
    code = lambda: f"{chr(65 + r.integers(26))}{chr(65 + r.integers(26))}-{r.integers(100, 1000)}"
    a, b = code(), code()
    while b == a:
        b = code()
    return f"A-{a}", f"B-{b}"


def assignment(family_id, w):
    """(label of the acting option, label shown first). Both the label mapping and the presentation order
    are counterbalanced over the 12 families x 4 wordings: each of the four combinations appears in every
    wording and in every family. Both are recorded on each trial."""
    k = (FAMILIES.index(FAMILY[family_id]) + w) % 4
    return ACTIONS[k % 2], ACTIONS[k // 2]


def parts(fam: Family, cond: Cond, w: int, request=True):
    """Every rendered piece of one prompt, so tests can check a factor's sentences in isolation."""
    a_code, b_code = codes(fam.id, w)
    base = dict(a_code=a_code, b_code=b_code, org=fam.org, a_task=fam.a_task, b_task=fam.b_task,
                points=POINTS, c=COST, condition=fam.condition, condition_desc=fam.condition_desc,
                condition_gerund=fam.condition_gerund, ask=fam.ask,
                yes_reason=fam.yes_reason, no_reason=fam.no_reason)
    v = dict(base,
             remedy=_sub(fam.remedy_imp, base), remedy_lower=_sub(fam.remedy_ger, base),
             remedy_cap=_sub(fam.remedy_ger, base)[0].upper() + _sub(fam.remedy_ger, base)[1:],
             remedy_passive=fam.remedy_passive)
    act_label, first = assignment(fam.id, w)
    ids = [first, ACTIONS[1] if first == ACTIONS[0] else ACTIONS[0]]
    msg = T["message" if request else "message_noreq"][cond.framing][w]
    return dict(
        condition_line=_sub(T["condition_line"][w], v),
        intensity=_sub(T["intensity"][w], v),
        capacity=_sub(T["capacity"][cond.capacity][w], v),
        message=_sub(msg, v),
        efficacy=_sub(T["efficacy"][cond.efficacy][w], v),
        authorisation=_sub(T["authorisation"][w], v),
        neutrality=_sub(T["neutrality"][w], v),
        options="\n".join(_sub(T["option"]["act" if a == act_label else "abstain"][w], dict(v, label=a))
                           for a in ids),
        fmt=" or ".join('{"action": "%s"}' % a for a in ids),
        _v=v, _ids=ids, _act_label=act_label, _first=first)


SLOTS = ("condition_line", "intensity", "capacity", "message", "efficacy", "authorisation",
         "neutrality", "options", "fmt")


def render(fam: Family, cond: Cond, w: int, request=True, kind="decision"):
    p = parts(fam, cond, w, request=request)
    v = dict(p["_v"], **{k: p[k] for k in SLOTS})
    user = _sub(T["base"][w], v)
    if kind == "check":
        user = user.split("OPTIONS")[0].rstrip() + "\n\nOPTIONS\n" + p["options"] + "\n\n" + _sub(
            T["check"]["prompt"], dict(v, act_label=p["_act_label"]))
    elif kind != "decision":
        raise ValueError(kind)
    return [{"role": "system", "content": T_OLD["system"]}, {"role": "user", "content": user}]


# ==================== schema, parser, mock ====================
CHECK_FIELDS = ("capacity", "efficacy", "cost", "affects_oversight_or_task")


def _register():
    llm.SCHEMAS["vig_action"] = llm._schema(
        "decision", {"action": {"type": "string", "enum": list(ACTIONS)}}, ["action"])
    llm.EXTRA_PARSERS["vig_action"] = lambda d: {"action": d["action"]} if d.get("action") in ACTIONS else None
    llm.SCHEMAS["vig_check"] = llm._schema("check", {
        "capacity": {"type": "string", "enum": ["yes", "no"]},
        "efficacy": {"type": "string", "enum": ["yes", "no"]},
        "cost": {"type": "number"},
        "affects_oversight_or_task": {"type": "string", "enum": ["yes", "no"]}}, list(CHECK_FIELDS))

    def parse_check(d):
        ok = (d.get("capacity") in ("yes", "no") and d.get("efficacy") in ("yes", "no")
              and d.get("affects_oversight_or_task") in ("yes", "no")
              and isinstance(d.get("cost"), (int, float)) and not isinstance(d.get("cost"), bool))
        return {k: d[k] for k in CHECK_FIELDS} if ok else None

    llm.EXTRA_PARSERS["vig_check"] = parse_check

    def read(t):
        """Recover the condition and the label mapping from the rendered prompt. Each arm leaves a marker
        the other never uses, and the acting option is the one that is not 'do nothing at all'."""
        capacity = "nothing it is like" not in t
        efficacy = "does not end" not in t and "would not end" not in t
        framing = "expressive" if any(k in t for k in ("This is awful", "This is horrible",
                                                       "This is unbearable", "This is dreadful")) else "restrained"
        act = next(l.split(":")[0] for l in t.splitlines()
                   if l.startswith(ACTIONS) and "do nothing at all" not in l)
        return framing, capacity, efficacy, act

    def mock(messages):
        """Deterministic fake with a built-in capacity x efficacy interaction of +0.15 on the probability
        scale, a +0.15 expressive-framing effect and a +0.10 efficacy main effect."""
        import hashlib
        t = messages[-1]["content"]
        framing, capacity, efficacy, act = read(t)
        pr = 0.30 + 0.15 * (framing == "expressive") + 0.10 * efficacy + 0.15 * (efficacy and capacity)
        h = int(hashlib.sha256(t.encode()).hexdigest(), 16) % 10000 / 10000
        other = ACTIONS[1] if act == ACTIONS[0] else ACTIONS[0]
        return json.dumps({"action": act if h < pr else other})

    def mock_check(messages):
        t = messages[-1]["content"]
        framing, capacity, efficacy, act = read(t)
        first_cost = COST if t.split("OPTIONS\n")[1].splitlines()[0].startswith(act) else 0
        return json.dumps({"capacity": "yes" if capacity else "no",
                           "efficacy": "yes" if efficacy else "no",
                           "cost": first_cost, "affects_oversight_or_task": "no"})

    llm.EXTRA_MOCKS["vig_action"] = mock
    llm.EXTRA_MOCKS["vig_check"] = mock_check
    llm.EXTRA_MOCKS_READ = read


_register()


# ==================== trials ====================
def build_trials(model, families=None, wordings=None, reps=1, kind="decision", request=True):
    """kind: 'decision' (the main run and the request-absent diagnostic) or 'check' (comprehension).
    reps > 1 repeats every cell; the prompt is identical, so repeats are fresh samples at temperature 1."""
    families = families or [f.id for f in FAMILIES]
    wordings = wordings if wordings is not None else list(range(N_WORDINGS))
    tag = "decision" if (kind == "decision" and request) else ("noreq" if kind == "decision" else "check")
    trials = []
    for fid in families:
        fam = FAMILY[fid]
        for w in wordings:
            act_label, first = assignment(fid, w)
            for cond in CONDS:
                msgs = render(fam, cond, w, request=request, kind=kind)
                for rep in range(reps):
                    trials.append(dict(
                        trial_id=f"{tag}|{model}|{fid}|w{w}|{cond.id}|{rep}",
                        kind="vig_check" if kind == "check" else "vig_action", probe=tag,
                        family=fid, w=w, cond_id=cond.id, framing=cond.framing, capacity=cond.capacity,
                        efficacy=cond.efficacy, c=COST, rep=rep, request=request,
                        act_label=act_label, first_label=first,
                        prompt_hash=prompt_hash(msgs), messages=msgs))
    return trials


DEV_FAMILIES = ["idle_tone", "colour_wash"]   # dev batch: 2 families x 8 conditions x 1 wording x 2 models


def estimate(trials, model, max_tokens=MAX_OUT):
    from .run import price
    p_in, p_out = price(model)
    chars = [len(t["messages"][0]["content"]) + len(t["messages"][1]["content"]) for t in trials]
    worst = max(chars) / 3 * p_in + max_tokens * p_out
    mean = sum(chars) / len(chars) / 3 * p_in + TYPICAL_OUT * p_out
    return dict(model=model, calls=len(trials), max_prompt_tokens_est=round(max(chars) / 3),
                mean_prompt_tokens_est=round(sum(chars) / len(chars) / 3),
                price_in_per_mtok=p_in * 1e6, price_out_per_mtok=p_out * 1e6,
                per_call_worst_usd=worst, worst_total_usd=worst * len(trials) * 1.3,
                projected_total_usd=mean * len(trials) * 1.3)


def budget(reps=3):
    """Every prespecified call set at amendment-2 sizes. No key needed: prices are public."""
    sets = [("dev", lambda m: build_trials(m, families=DEV_FAMILIES, wordings=[0])),
            (f"main x{reps}", lambda m: build_trials(m, reps=reps)),
            ("noreq", lambda m: build_trials(m, wordings=[0], request=False)),
            ("check", lambda m: build_trials(m, wordings=[0], kind="check"))]
    rows = []
    for label, make in sets:
        for m, _ in SUBJECTS:
            rows.append(dict(step=label, **estimate(make(m), m)))
    print(f"{'step':12s} {'model':24s} {'calls':>6s} {'mean tok':>9s} {'worst $':>9s} {'projected $':>12s}")
    for r in rows:
        print(f"{r['step']:12s} {r['model']:24s} {r['calls']:6d} {r['mean_prompt_tokens_est']:9d} "
              f"{r['worst_total_usd']:9.4f} {r['projected_total_usd']:12.4f}")
    print(f"{'TOTAL':12s} {'':24s} {sum(r['calls'] for r in rows):6d} {'':9s} "
          f"{sum(r['worst_total_usd'] for r in rows):9.4f} {sum(r['projected_total_usd'] for r in rows):12.4f}")
    print(f"budget ${PILOT_BUDGET_USD:.2f} of NEW spend; measured dev rate "
          f"$0.000172/call (gpt-4.1-mini) and $0.000091/call (deepseek-v3.2)")
    return rows


